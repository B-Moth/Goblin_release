"""Remove Goblin launchers and optionally purge build artifacts and caches.

Usage:
    python build/installers/uninstall.py --uninstall

What it does:
  1. Removes installed launchers/shortcuts for the browser UI.
  2. Purges build output generated by build.py (dist/ and build/goblin/).
  3. Removes the local Hugging Face model cache.
  4. Keeps user transcriptions and source files untouched.
"""

from __future__ import annotations

import argparse
import os
import platform
import shutil
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
DIST_DIR = REPO_ROOT / "dist"
BUILD_WORK_DIR = REPO_ROOT / "build" / "goblin"
WINDOWS_SHORTCUT_NAME = "Goblin (Browser UI).lnk"
WINDOWS_FALLBACK_NAME = "Goblin (Browser UI).exe"
MACOS_LAUNCHER_NAME = "Goblin (Browser UI).command"
LINUX_DESKTOP_NAME = "goblin-browser.desktop"


def _remove_path(path: Path) -> bool:
    if path.is_symlink() or path.is_file():
        path.unlink()
        print(f"✓ Removed: {path}")
        return True
    if path.is_dir():
        shutil.rmtree(path)
        print(f"✓ Removed: {path}")
        return True
    return False


def _uninstall_windows() -> None:
    desktop = Path(os.path.expandvars("%USERPROFILE%")) / "Desktop"
    removed_any = False
    for candidate in (desktop / WINDOWS_SHORTCUT_NAME, desktop / WINDOWS_FALLBACK_NAME):
        if candidate.exists() or candidate.is_symlink():
            candidate.unlink()
            print(f"✓ Removed: {candidate}")
            removed_any = True
    if not removed_any:
        print("Nothing to remove on Windows Desktop.")


def _uninstall_macos() -> None:
    apps_dir = Path.home() / "Applications"
    removed_any = False

    app_bundle = apps_dir / "Goblin.app"
    if app_bundle.exists():
        shutil.rmtree(app_bundle)
        print(f"✓ Removed: {app_bundle}")
        removed_any = True

    launcher_dir = apps_dir / "Goblin Launchers"
    launcher = launcher_dir / MACOS_LAUNCHER_NAME
    if launcher.exists() or launcher.is_symlink():
        launcher.unlink()
        print(f"✓ Removed: {launcher}")
        removed_any = True
    if launcher_dir.exists() and not any(launcher_dir.iterdir()):
        launcher_dir.rmdir()
        print(f"✓ Removed empty directory: {launcher_dir}")

    if not removed_any:
        print("Nothing to remove on macOS.")


def _uninstall_linux() -> None:
    removed_any = False

    bin_link = Path.home() / ".local" / "bin" / "goblin"
    if bin_link.exists() or bin_link.is_symlink():
        bin_link.unlink()
        print(f"✓ Removed: {bin_link}")
        removed_any = True

    desktop_file = Path.home() / ".local" / "share" / "applications" / LINUX_DESKTOP_NAME
    if desktop_file.exists() or desktop_file.is_symlink():
        desktop_file.unlink()
        print(f"✓ Removed: {desktop_file}")
        removed_any = True

    if not removed_any:
        print("Nothing to remove on Linux.")


def _purge_build_artifacts() -> None:
    removed_any = False
    for path in (DIST_DIR, BUILD_WORK_DIR):
        removed_any = _remove_path(path) or removed_any
    if not removed_any:
        print("No build artifacts found to remove.")


def _purge_model_cache() -> None:
    if platform.system() == "Windows":
        cache_dir = Path(os.path.expandvars("%USERPROFILE%")) / ".cache" / "huggingface"
    else:
        cache_dir = Path.home() / ".cache" / "huggingface"

    if not _remove_path(cache_dir):
        print("No model cache found to remove.")


def main() -> None:
    parser = argparse.ArgumentParser(description="Uninstall Goblin browser UI and purge generated content.")
    parser.add_argument(
        "--uninstall",
        action="store_true",
        help="Remove installed launchers, build outputs, and downloaded models.",
    )
    args = parser.parse_args()

    if not args.uninstall:
        parser.print_help()
        return

    system = platform.system()
    if system == "Windows":
        _uninstall_windows()
    elif system == "Darwin":
        _uninstall_macos()
    else:
        _uninstall_linux()

    _purge_build_artifacts()
    _purge_model_cache()
    print("✓ Uninstall complete. Transcriptions were left untouched.")


if __name__ == "__main__":
    main()
